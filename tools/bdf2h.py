#!/usr/bin/env python3
"""Spleen's BDFs into src/vk/fonts/spleen.h: the GPU backend's glyph
atlases (VK_DESIGN.md; first written for ../syNESthesia). A glyph is a
row a word, bit 31 its leftmost pixel; an atlas is 256 glyphs, the index
the codepoint for Latin-1's printable ones (0x20-0x7e, 0xa0-0xff) and the
extras below in the slots left (0x01-0x1f, 0x7f-0x9f).
Usage: bdf2h.py OUT.h FONT.bdf..."""

import sys

EXTRAS = (
    "─│┌┐└┘├┤┬┴┼═║╔╗╚╝"  # box drawing
    "←↑→↓▲▼"  # arrows, triangles (▶◀ and ✓✗ are in none: drawn)
    "█▀▄▌▐░▒▓"  # blocks
    "●○•◆♪…"
)


def slots():
    return list(range(0x01, 0x20)) + list(range(0x7F, 0xA0))


def parse(path):
    glyphs, w, h, cur, rows, bbx, asc = {}, 0, 0, None, None, None, 0
    with open(path, encoding="latin-1") as f:
        lines = f.readlines()
    for line in lines:
        t = line.split()
        if not t:
            continue
        if t[0] == "FONTBOUNDINGBOX":
            w, h, _, fy = map(int, t[1:5])
            asc = h + fy
        elif t[0] == "ENCODING":
            cur = int(t[1])
        elif t[0] == "BBX":
            bbx = list(map(int, t[1:5]))
        elif t[0] == "BITMAP":
            rows = []
        elif t[0] == "ENDCHAR":
            _, bh, bx, by = bbx
            out = [0] * h
            top = asc - (bh + by)
            for i, r in enumerate(rows):
                bits = int(r, 16) << (32 - len(r) * 4)
                y = top + i
                if 0 <= y < h:
                    out[y] = (bits >> bx) & 0xFFFFFFFF
            glyphs[cur] = out
            rows = None
        elif rows is not None:
            rows.append(t[0])
    return w, h, glyphs


def main():
    out, fonts = sys.argv[1], sys.argv[2:]
    extra = dict(zip(slots(), EXTRAS, strict=False))
    assert len(EXTRAS) <= len(slots())
    o = [
        "/* Generated by tools/bdf2h.py from Spleen 2.2.0 (Frederic Cambus,",
        " * BSD-2-Clause, src/vk/fonts/LICENSE.spleen): the glyph atlases,",
        " * 256 glyphs of h rows each, a row a word, bit 31 the leftmost pixel.",
        " * Index: Latin-1's printable codepoints as themselves; the extras in",
        " * the slots between (UI_FONT_EXTRAS, the same order) */",
        "",
        "#include <stdint.h>",
        "",
        f'#define UI_FONT_EXTRAS "{EXTRAS}"',
    ]
    slot_list = ", ".join(f"0x{s:02x}" for s in slots()[: len(EXTRAS)])
    o.append(f"static const uint8_t k_ui_font_extra_slot[] = {{{slot_list}}};")
    o.append("")
    names = []
    for path in fonts:
        w, h, g = parse(path)
        name = f"k_ui_font_{w}x{h}"
        names.append((name, w, h))
        missing = []
        o.append(f"static const uint32_t {name}[256 * {h}] = {{")
        for i in range(256):
            cp = ord(extra[i]) if i in extra else i
            printable = i in extra or 0x20 <= i <= 0x7E or 0xA0 <= i <= 0xFF
            rows = g.get(cp) if printable else None
            if printable and rows is None:
                missing.append(chr(cp))
            rows = rows or [0] * h
            o.append("    " + ", ".join(f"0x{r:08x}" for r in rows) + ",")
        o.append("};")
        if missing:
            print(f"{name}: missing {''.join(missing)}", file=sys.stderr)
    o.append("")
    o.append(
        "typedef struct {\n  unsigned w, h;\n  const uint32_t *rows;\n} UI_FONT_SIZE;"
    )
    o.append("static const UI_FONT_SIZE k_ui_fonts[] = {")
    for n, w, h in names:
        o.append(f"    {{{w}, {h}, {n}}},")
    o.append("};")
    with open(out, "w") as f:
        f.write("\n".join(o) + "\n")


main()
