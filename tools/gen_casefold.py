#!/usr/bin/env python3
"""Generates src/query/casefold.h: Unicode's simple case folding (what a
case-blind match compares), as runs, from the Unicode Character Database.

    tools/gen_casefold.py [--ucd DIR] [--check]

--ucd reads CaseFolding.txt from DIR; without it the file is fetched once
for UNICODE_VERSION (gen_utf8_props.py's) into ~/.cache/ctui/ucd-VERSION/.
--check exits 1 when the checked-in header differs from what the data
gives (drift).

Only the C and S mappings (one codepoint to one): the full ones (F: "ß"
-> "ss") change a string's length in codepoints, which a match over
folded text doesn't need. A run is first..last where every stride-th
codepoint maps to itself + delta (stride 2: the alternating upper/lower
pairs of Latin Extended-A and friends); the codepoints between do not
fold.
"""

import argparse
import os
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_utf8_props import UNICODE_VERSION  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src',
                   'query', 'casefold.h')


def ucd_file(arg):
    d = arg or os.path.expanduser(f'~/.cache/ctui/ucd-{UNICODE_VERSION}')
    path = os.path.join(d, 'CaseFolding.txt')
    if not arg and not os.path.exists(path):
        os.makedirs(d, exist_ok=True)
        url = f'https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/CaseFolding.txt'
        with urllib.request.urlopen(url) as r, open(path + '.tmp', 'wb') as f:
            f.write(r.read())
        os.rename(path + '.tmp', path)
    return path


def folds(path):
    out = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            cp, status, mapping = [x.strip() for x in line.split(';')[:3]]
            if status in ('C', 'S'):
                out[int(cp, 16)] = int(mapping, 16)
    return out


def runs(m):
    """[first, last, delta, stride], greedily: extend a run while the next
    folding codepoint is stride on with the same delta"""
    out = []
    for cp in sorted(m):
        delta = m[cp] - cp
        if out:
            r = out[-1]
            gap = cp - r[1]
            if r[2] == delta and (gap == r[3] or (r[0] == r[1] and gap in (1, 2))):
                r[3] = gap
                r[1] = cp
                continue
        out.append([cp, cp, delta, 1])
    return out


def render(rs):
    rows = '\n'.join(f'    {{0x{a:05X}, 0x{b:05X}, {d}, {s}}},' for a, b, d, s in rs)
    return f'''/* generated by tools/gen_casefold.py from Unicode {UNICODE_VERSION} --
 * do not edit; re-run it (--check shows drift). Simple case folding as
 * sorted runs: in first..last, every stride-th codepoint from first folds
 * to itself + delta. */
#ifndef CTUI_QUERY_CASEFOLD_H
#define CTUI_QUERY_CASEFOLD_H

#include <stdint.h>

/* clang-format off */
static const struct {{
  uint32_t first, last;
  int32_t delta;
  uint8_t stride;
}} ctui_casefold_table[] = {{
{rows}
}};
/* clang-format on */

#endif
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ucd')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render(runs(folds(ucd_file(a.ucd))))
    if a.check:
        with open(OUT, encoding='utf-8') as f:
            if f.read() != text:
                print('casefold.h differs from the data: re-run', file=sys.stderr)
                return 1
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
