#ifndef CTUI_WL_H
#define CTUI_WL_H

/* Wayland surfaces of an app's own (VK_DESIGN.md "A window"): a
 * connection (CTUI_WL_DPY: the seat, the outputs, the input queue) and
 * its surfaces (CTUI_WL) -- an xdg_toplevel here, a layer of the desktop
 * through layer.h. Each surface has the scale the compositor wants
 * (fractional through a viewport onto a buffer of real pixels, or whole)
 * and the display's timing (wp_presentation); input comes as ctui's
 * events, each naming the surface it's for -- keys through xkbcommon (the
 * keymap the compositor sends, compose and dead keys, repeats on a
 * timerfd at the compositor's rate) to the surface with the keyboard, the
 * pointer as mouse events on the cells under it. Mapped as a terminal's
 * legacy bytes would be, so a handler can't tell the window from a
 * terminal: ctrl+letter its control byte, Backspace 0x7f, shift+Tab
 * BACKTAB.
 *
 * One window alone: ctui_wl_open() connects and opens it, and the
 * ctui_wl_*() calls on it stand for its connection's. Several surfaces
 * (a desktop's panels): ctui_wl_connect(), then ctui_wl_window() /
 * ctui_wl_layer() on it, ctui_wl_dpy_next() saying which one an event is
 * for.
 *
 * What draws into them is the caller's (src/vk/ and a swapchain): here
 * the surfaces and their sizes. Optional like src/vk/: built where
 * wayland-client, its scanner and protocols, and xkbcommon are; the
 * protocols' glue is generated by the consumer's build (xdg-shell,
 * viewporter, fractional-scale-v1, cursor-shape-v1 with tablet-v2,
 * presentation-time; layer.c adds ctui's protocols/wlr-layer-shell).
 *
 * Promoted from ctui-mus's window host, its second user syNESthesia. */

#include "ctui.h"

#include <stdint.h>

struct wl_display;
struct wl_surface;

typedef struct CTUI_WL_DPY CTUI_WL_DPY;
typedef struct CTUI_WL CTUI_WL;

/* --- the connection --- */

/* NULL when there's no compositor or no keymap context (why in err) */
CTUI_WL_DPY *ctui_wl_connect(char *err, unsigned n);
/* its surfaces closed first */
void ctui_wl_disconnect(CTUI_WL_DPY *d);
struct wl_display *ctui_wl_dpy_display(CTUI_WL_DPY *d);

/* the fds to wait on: the connection, and the key repeat's timerfd */
int ctui_wl_dpy_fd(CTUI_WL_DPY *d);
int ctui_wl_dpy_repeat_fd(CTUI_WL_DPY *d);
/* reads what's on the connection and runs the handlers (0, or -1 when
 * it's gone); a repeat's timer having fired, its keys queued */
int ctui_wl_dpy_dispatch(CTUI_WL_DPY *d);
void ctui_wl_dpy_repeat(CTUI_WL_DPY *d);
/* the requests out, before waiting: what's queued dispatched first (a
 * present may have read the connection). 1 when a surface's frame
 * callback came in since the last flush (ctui_wl_frame()): a frame held
 * back is due, so present again before waiting */
int ctui_wl_dpy_flush(CTUI_WL_DPY *d);

/* the next input event queued, its data valid until the next call, and
 * the surface it's for in *on (if on isn't NULL): 1, or 0 for none. An
 * event whose surface closed while it waited is dropped */
int ctui_wl_dpy_next(CTUI_WL_DPY *d, CTUI_EVENT *ev, CTUI_WL **on);
/* CTUI_FOCUS_EVENTs as a surface gets and loses the keyboard (off by
 * default, as ctui_focus_enable() is a terminal's) */
void ctui_wl_dpy_focus_events(CTUI_WL_DPY *d, int on);

/* the outputs' names (wl_output 4), up to max of them into names (valid
 * until the next dispatch); how many there are */
int ctui_wl_outputs(const CTUI_WL_DPY *d, const char **names, int max);

/* --- a surface --- */

/* a window w x h logical pixels on d; NULL when the compositor lacks
 * xdg-shell (why in err) */
CTUI_WL *ctui_wl_window(CTUI_WL_DPY *d, const char *title, const char *app_id,
                        int w, int h, char *err, unsigned n);
/* a connection of its own and a window on it: NULL as either would be.
 * Closing it disconnects */
CTUI_WL *ctui_wl_open(const char *title, const char *app_id, int w, int h,
                      char *err, unsigned n);
void ctui_wl_close(CTUI_WL *wl);

CTUI_WL_DPY *ctui_wl_dpy(CTUI_WL *wl);
struct wl_display *ctui_wl_display(CTUI_WL *wl);
struct wl_surface *ctui_wl_surface(CTUI_WL *wl);
/* the caller's own pointer, for an event's surface back to its state */
void ctui_wl_set_user(CTUI_WL *wl, void *user);
void *ctui_wl_user(const CTUI_WL *wl);

/* its connection's (above), for a window alone */
int ctui_wl_fd(CTUI_WL *wl);
int ctui_wl_repeat_fd(CTUI_WL *wl);
int ctui_wl_dispatch(CTUI_WL *wl);
void ctui_wl_repeat(CTUI_WL *wl);
int ctui_wl_flush(CTUI_WL *wl);
int ctui_wl_next(CTUI_WL *wl, CTUI_EVENT *ev);
int ctui_wl_queued(const CTUI_WL *wl);

/* every key by its evdev code (linux/input-event-codes.h: a position,
 * whatever the layout), pressed (down 1) or released (0), before it
 * becomes a ctui event; (0, 0) when the keyboard's focus went, so
 * nothing stays held. A press it returns 1 for is taken: no event, no
 * repeat. For an app with keys of its own beside ctui's (a game's
 * buttons); NULL: none. Its connection's, whichever surface has the keys */
typedef int (*CTUI_WL_RAW_KEY)(void *ctx, unsigned evdev, int down);
void ctui_wl_set_raw_key(CTUI_WL *wl, CTUI_WL_RAW_KEY fn, void *ctx);

/* the buffer's size in real pixels; 1 when it changed since the last
 * call. Before the first configure, the size asked for */
int ctui_wl_size(CTUI_WL *wl, int *pw, int *ph);
/* its size in logical pixels, as the compositor last configured it */
void ctui_wl_logical(const CTUI_WL *wl, int *w, int *h);
/* the viewport (or buffer scale) for that buffer, before the commit
 * that first shows it */
void ctui_wl_viewport(CTUI_WL *wl);
/* the scale buffer pixels are drawn at, in 120ths (1.5: 180) */
int ctui_wl_scale120(CTUI_WL *wl);
/* the cell's size in buffer pixels: the pointer's cells */
void ctui_wl_cell(CTUI_WL *wl, int cw, int ch);
/* where the cells start, in buffer pixels (0, 0 until said): the
 * pointer's cells and pixels counted from there */
void ctui_wl_cell_origin(CTUI_WL *wl, int x, int y);
/* the pointer's shape over the surface, by its CSS cursor name
 * (ctui_pointer_shape()'s: "pointer", "text", "ew-resize", ...; NULL,
 * "" or one cursor-shape-v1 lacks: the default arrow): at once while
 * the pointer's on it, else when it next comes. Nothing without the
 * compositor's cursor-shape-v1 */
void ctui_wl_pointer_shape(CTUI_WL *wl, const char *name);

/* the display's timing: ask for the next commit's feedback (before the
 * present that commits), tagged with the host's time then
 * (CLOCK_MONOTONIC ns); what came back */
typedef struct {
  int clock_ok; /* the compositor's clock is MONOTONIC */
  uint64_t asked, presented, discarded;
  double lat_sum, lat_min, lat_max; /* ns, the tag to the light */
  uint64_t refresh_ns;              /* the display's period, as it says */
  uint64_t last_ns, last_seq;       /* the latest presented's time, vblank */
  uint64_t vsync, zero_copy;        /* flags: tear-free, scanned out direct */
} CTUI_WL_TIMING;
void ctui_wl_feedback(CTUI_WL *wl, uint64_t tag_ns);
const CTUI_WL_TIMING *ctui_wl_timing(const CTUI_WL *wl);

/* the compositor's pacing: ask for a frame callback on the next commit
 * (before the present that commits; one at a time), and whether it's
 * still to come. A surface the compositor doesn't show -- under a
 * fullscreen window, on a workspace not shown -- gets none until it's
 * shown again: a presenter that waits for it (src/vk/present.c) never
 * blocks on a frame nobody will see. Cancelled when the commit didn't
 * happen (a present that failed), or nothing would ever answer it */
void ctui_wl_frame(CTUI_WL *wl);
void ctui_wl_frame_cancel(CTUI_WL *wl);
int ctui_wl_frame_waiting(const CTUI_WL *wl);

/* the compositor closed it (a window's close button, a layer's output
 * unplugged) */
int ctui_wl_closed(const CTUI_WL *wl);
/* a window's; nothing for another surface */
void ctui_wl_title(CTUI_WL *wl, const char *title);

/* the key event a keysym makes (cp: its character, xkbcommon's utf32, 0
 * for none) with mods (CTUI_MOD_*) held, as the terminal's bytes would:
 * 1, or 0 for a key that makes none (a modifier alone) */
int ctui_wl_key_event(uint32_t sym, uint32_t cp, unsigned mods,
                      CTUI_KEYPRESS_EVENT_DATA *out);
/* the event's base (CTUI_KEYPRESS_EVENT_DATA's, kitty's base layout key)
 * for the key code (xkb's) in keymap km: its unshifted char in the
 * keymap's first layout -- on a US keymap the US place -- when that
 * differs from ch; 0 else (no char, a control) */
struct xkb_keymap;
uint32_t ctui_wl_key_base(struct xkb_keymap *km, uint32_t code, uint32_t ch);

#endif
